def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


def _count(result: ScanResult, severity: Severity) -> int:
    return sum(1 for finding in result.open_findings if finding.severity == severity)


def _grade_color(grade: str) -> str:
    return {
        "A": "#2ec4a6",
        "B": "#8ac926",
        "C": "#ffd23f",
        "D": "#ff8a3d",
        "F": "#ff3b5c",
    }.get(grade, "#7d8597")


def build_html(result: ScanResult) -> str:
    """Render a single self-contained HTML report."""
    rows: List[str] = []
    if not result.open_findings:
        rows.append(
            f'<tr><td colspan="5" class="empty">No open ports on the probed set.</td></tr>'
        )
    for finding in result.open_findings:
        color = SEVERITY_COLORS[finding.severity]
        rows.append(
            "<tr>"
            f'<td class="port">{finding.port}</td>'
            f"<td>{html.escape(finding.service)}</td>"
            f'<td><span class="chip" style="background:{color}22;color:{color}">'
            f"{finding.severity.value}</span></td>"
            f"<td>{html.escape(finding.note or '-')}</td>"
            f'<td class="banner">{html.escape(finding.banner or "-")}</td>'
            "</tr>"
        )

    table = (
        "<table><thead><tr><th>Port</th><th>Service</th><th>Severity</th>"
        "<th>Why it matters</th><th>Banner</th></tr></thead><tbody>"
        + "".join(rows)
        + "</tbody></table>"
    )

    nmap_section = ""
    if result.nmap:
        nmap_section = (
            "<h2>Nmap enrichment</h2><pre>"
            + html.escape(json.dumps(result.nmap, indent=2))
            + "</pre>"
        )

    return HTML_TEMPLATE.format(
        target=html.escape(result.target),
        address=html.escape(result.address),
        open_count=len(result.open_findings),
        port_count=len(result.ports),
        started=result.started_at.strftime("%Y-%m-%d %H:%M:%S UTC"),
        duration=f"{result.duration_seconds:.1f}s",
        grade=result.risk_grade,
        grade_color=_grade_color(result.risk_grade),
        finding_count=len(result.open_findings),
        critical=_count(result, Severity.CRITICAL),
        critical_color=SEVERITY_COLORS[Severity.CRITICAL],
        high=_count(result, Severity.HIGH),
        high_color=SEVERITY_COLORS[Severity.HIGH],
        port_table=table,
        nmap_section=nmap_section,
        generated=_now(),
    )


def build_markdown(result: ScanResult) -> str:
    """Render a Markdown summary suitable for pasting into a ticket."""
    lines = [
        f"# ReconX report: {result.target}",
        "",
        f"- **Address:** `{result.address}`",
        f"- **Started:** {result.started_at.strftime('%Y-%m-%d %H:%M:%S UTC')}",
        f"- **Duration:** {result.duration_seconds:.1f}s",
        f"- **Ports probed:** {len(result.ports)}",
        f"- **Open ports:** {len(result.open_findings)}",
        f"- **Risk grade:** {result.risk_grade} (score {result.risk_score})",
        "",
        "## Open ports",
        "",
    ]

    if not result.open_findings:
        lines.append("_No open ports on the probed set._")
    else:
        lines += ["| Port | Service | Severity | Why it matters |", "| ---: | --- | --- | --- |"]
        for finding in result.open_findings:
            note = (finding.note or "-").replace("|", "\\|")
            lines.append(
                f"| {finding.port} | {finding.service} | {finding.severity.value} | {note} |"
            )

    if result.nmap:
        lines += ["", "## Nmap enrichment", "", "```json", json.dumps(result.nmap, indent=2), "```"]

    lines += [
        "",
        "---",
        "",
        "_Generated by ReconX. Only scan systems you own or have written authorization to test._",
        "",
    ]
    return "\n".join(lines)


def build_json(result: ScanResult) -> Dict[str, object]:
    """Render the machine-readable report payload."""
    return {
        "tool": "ReconX",
        "schema": "reconx.report/2",
        "generated": _now(),
        "target": result.target,
        "address": result.address,
        "started_at": result.started_at.isoformat(),
        "finished_at": result.finished_at.isoformat(),
        "duration_seconds": round(result.duration_seconds, 2),
        "ports_probed": list(result.ports),
        "risk_score": result.risk_score,
        "risk_grade": result.risk_grade,
        "findings": [finding.as_row() for finding in result.open_findings],
        "nmap": result.nmap,
        "disclaimer": "Only scan systems you own or have written authorization to test.",
    }


def write_csv(result: ScanResult, path: str) -> str:
    """Write findings to CSV (one row per open port)."""
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "port",
                "state",
                "service",
                "product",
                "severity",
                "note",
                "latency_ms",
                "banner",
            ],
        )
        writer.writeheader()
        for finding in result.open_findings:
            writer.writerow(finding.as_row())
    return path


def write_reports(
    result: ScanResult,
    out_dir: str,
    formats: Sequence[str] = ("json", "csv", "html", "md"),
) -> Dict[str, str]:
    """Write every requested format and return ``{format: path}``."""
    os.makedirs(out_dir, exist_ok=True)
    safe_host = "".join(ch if ch.isalnum() or ch in ".-_" else "_" for ch in result.target)
    stamp = result.started_at.strftime("%Y%m%d-%H%M%S")
    written: Dict[str, str] = {}

    if "json" in formats:
        path = os.path.join(out_dir, f"{safe_host}-{stamp}.json")
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(build_json(result), handle, indent=2)
        written["json"] = path

    if "csv" in formats:
        written["csv"] = write_csv(
            result, os.path.join(out_dir, f"{safe_host}-{stamp}.csv")
        )

    if "html" in formats:
        path = os.path.join(out_dir, f"{safe_host}-{stamp}.html")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(build_html(result))
        written["html"] = path

    if "md" in formats:
        path = os.path.join(out_dir, f"{safe_host}-{stamp}.md")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(build_markdown(result))
        written["md"] = path

    return written
